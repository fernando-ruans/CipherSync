export type DictKey = keyof typeof dict['pt-BR']

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
    const table = (dict as Record<string, Record<string, string>>)[lang] ?? dict['pt-BR']
    let s = table[key] ?? (dict['pt-BR'] as Record<string, string>)[key] ?? key
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            s = s.split(`{${k}}`).join(String(v))
        }
    }
    return s
}

// useT subscribes to the language so components re-render on switch.
export function useT(): (key: DictKey | string, vars?: Record<string, string | number>) => string {
    const lang = useApp((s) => s.lang)
    return (key: DictKey | string, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

